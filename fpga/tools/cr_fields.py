#!/usr/bin/env python3
"""cr_fields.py - what cr_core.v publishes to the screen program (ui_composer), Stage 1/2 style:
fields[24*k +: 24] = 24-bit numbers (two's complement), conds[k] = booleans; field 0 is 0, cond 0 is 1.
Index = position in the list + 1. `python3 -I fpga/tools/cr_fields.py` writes rtl/stage3/cr_fields.vh.

Screen positions are world-frame pixels of render.py's 640 x 352 frame (before its NEAREST resize to 640 x 360),
rounded like Python's round(): x = round((pos - cam) * 32), y = round(352 - pos * 32).
Sprite ids are the order of cr_assets.sprite_images() (CR_SPR_* in cr_consts.vh); sizes from cr_stab.mem.
  P_X / P_Y      player: centre x, feet y (left = P_X - w // 2, top = P_Y - h)
  G1_X..G3_X     cloak ghosts' centre x (render.py:196-198), drawn while P_CLOAK
  P_CY           y of the flash ring centre (player feet + 1 m), FLASH = flash steps left
  R_*            reporter: centre x, feet y, id, label "?" y (R_LY), wall clip: source columns R_CL..R_CH-1
  A<k>_*         animal slot k (list order of the drawn animals): sprite id, centre x, bottom y, visible rows;
                 A_POP: the rows are the top rows of the sprite drawn above Y (an ant leaving its log);
                 otherwise the top rows of a sprite standing on Y (a walker sinking shows fewer rows);
                 A_FLY: the goose - the renderer adds its bob, round(-1.92 * sin(9 t)) px, t = NOW / 120 s
  ROUTE_FULL / ROUTE_PART  route bar: full cells, pixels of the next cell (hud.py:120-128)
Footprints (up to 72, PRINTS of them, oldest first) do not fit here: cr_core's read port q_idx -> q_data gives
  q_data[39:26] screen x (signed), [25:15] screen y (signed, render.py adds 1 + (side > 0)), [14:6] age in steps,
  [5:3] kind (0 snail 1 squirrel 2 ant 3 goose 4 boot), [2] direction -1, [1] side -1, [0] 0.
"""
import os

HERE = os.path.dirname(os.path.abspath(__file__))
N_SLOTS = 16

FIELDS_CR = (
    ["CAM_PX", "PAR", "NOW", "TIME_S", "SKILL_D", "PROGRESS", "ROUTE_FULL", "ROUTE_PART", "MSG", "Q0", "Q1",
     "INT_S", "FLASH", "STAGE", "PRINTS"]
    + ["P_X", "P_Y", "P_ID", "P_CY", "G1_X", "G2_X", "G3_X"]
    + ["R_X", "R_Y", "R_ID", "R_LY", "R_CL", "R_CH"]
    + ["TEA_X", "TEA_Y", "PUZ_X", "PUZ_Y", "L0_X", "L0_Y", "L1_X", "L1_Y"]
    + ["A%d_%s" % (i, k) for i in range(N_SLOTS) for k in ("ID", "X", "Y", "ROWS")]
)
CONDS_CR = (
    ["PLAY", "PAUSE", "CLEAR", "WIN", "NOTICE", "INTERVIEW", "QSEL", "SKILL_USED", "PHASE", "P_FLIP", "P_CLOAK",
     "R_ON", "R_FLIP", "R_LABEL", "TEA_ON", "OPENED", "PUZ_ON", "L0_ON", "L1_ON", "OVERFLOW"]
    + ["A%d_%s" % (i, k) for i in range(N_SLOTS) for k in ("V", "F", "POP", "FLY")]
)
assert len(FIELDS_CR) < 128 and len(CONDS_CR) < 252
FIELD = {n: i + 1 for i, n in enumerate(FIELDS_CR)}
COND = {n: i + 1 for i, n in enumerate(CONDS_CR)}


def pack(fields, conds):
    """(fields dict, conds dict) -> (int of 128 x 24 bits, int of 256 bits) as cr_core drives them"""
    fv = 0
    for name, v in fields.items():
        fv |= (v & 0xFFFFFF) << (24 * FIELD[name])
    cv = 1
    for name, v in conds.items():
        if v:
            cv |= 1 << COND[name]
    return fv, cv


def q_word(sx, sy, age, kind, direction, side):
    return ((sx & 0x3FFF) << 26 | (sy & 0x7FF) << 15 | (age & 0x1FF) << 6 | kind << 3 | (direction < 0) << 2
            | (side < 0) << 1)


def write_vh(path=os.path.join(HERE, "..", "rtl", "stage3", "cr_fields.vh")):
    with open(path, "w") as f:
        f.write("// cr_fields.vh - GENERATED by tools/cr_fields.py. Field k = fields[24*k +: 24], cond k = conds[k].\n")
        for n, i in FIELD.items():
            f.write("localparam integer CRF_%s = %d;\n" % (n, i))
        for n, i in COND.items():
            f.write("localparam integer CRC_%s = %d;\n" % (n, i))


if __name__ == "__main__":
    write_vh()
    print("cr_fields.vh: %d fields, %d conds" % (len(FIELDS_CR), len(CONDS_CR)))
