#!/usr/bin/env python3
"""stage3_assets.py - data for Stage 3 (graduation obby, demo_py/stage3_demo.py), taken from the demo itself.

Outputs:
  rtl/stage3/s3_consts.vh  solids (units of 1/(120*65536) m) + animal definitions + constants as Verilog functions
  mem/s3_solid.mem         solids for the renderer's TERRAIN primitive (screen-scale: 32 px per metre)
                           {kind 3b, x0 13b, x1 13b, y0 10b, y1 10b} (y signed)  x in world px, y = screen row (360 - m*32)
  mem/s3_txt.mem           Thai strings as 1-bit bitmaps (rendered with the demo's own Pygame font = same look)
  mem/s3_tidx.mem          per string {offset 16b, width 10b, height 6b}
  mem/sin256.mem           sin table, 256 entries per turn, signed 8 bit (x 127)
  tools/s3_text.json       string ids / sizes for the screen compiler
"""
import json
import math
import os
import sys

os.environ.setdefault("SDL_VIDEODRIVER", "dummy")
os.environ.setdefault("PYGAME_HIDE_SUPPORT_PROMPT", "1")
HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, "..", ".."))
sys.path.insert(0, os.path.join(ROOT, "demo_py"))
MEM = os.path.join(ROOT, "fpga", "mem")
RTL = os.path.join(ROOT, "fpga", "rtl", "stage3")
Q = 120 * 65536            # units per metre (see s3_model.py)


def q16(v):
    """metres -> RTL units (name kept: it used to be Q16)"""
    return int(round(v * Q))


KINDS = {"g": 1, "s": 2, "d": 3, "b": 4, "l": 5, "w": 6}

# Thai texts of stage3_demo.py (key names replaced by the board buttons). (id, text, font size, bold)
TEXTS = [
    ("TITLE", "เกมวิ่งข้ามน้ำ", 28, True),
    ("M1", "เดินหน้า/ถอยหลัง: BTNL BTNR   กระโดด: BTNU หรือ BTNC", 14, False),
    ("M2", "กด 2 ครั้งกลางอากาศ = กระโดดสูงและไกลขึ้น", 14, False),
    ("M3", "ชนสัตว์ 1 ครั้ง = นักข่าวตาม  ·  ชน 2 ครั้ง = หยุดคุย 5 วินาที", 14, False),
    ("M4", "กด BTND ใช้สกิลได้ 1 ครั้งต่อเกม ให้นักข่าวหลุดเฟรม  ·  ตกน้ำ = เริ่มใหม่", 14, False),
    ("M5", "เหยียบสัตว์ไม่ได้ — สัตว์ไม่หาย  ·  เวลาจำกัด 120 วินาที", 14, False),
    ("MSUB", "กด BTNC เพื่อเริ่ม", 14, False),
    ("WIN", "ถึงเส้นชัย!", 28, True),
    ("WIN_A", "ใช้เวลา ", 14, False), ("SEC", " วินาที", 14, False),
    ("WSUB", "กด BTNC เพื่อเล่นอีกครั้ง", 14, False),
    ("LOSE", "หมดเวลา!", 28, True),
    ("LOSE_A", "ไปได้ ", 14, False), ("LOSE_B", " จาก 250 เมตร", 14, False),
    ("LSUB", "กด BTNC เพื่อลองใหม่", 14, False),
    ("TIME", "เวลา ", 13, True),
    ("SKILL", "สกิล [BTND]: ", 13, True),
    ("SK_USED", "ใช้แล้ว", 13, True), ("SK_READY", "พร้อมใช้!", 13, True), ("SK_WAIT", "ใช้เมื่อโดนนักข่าวตาม", 13, True),
    ("MSG_SKILL", "สกิล! นักข่าวหลุดจากเฟรม", 13, True), ("MSG_HIT", "ชนสัตว์! นักข่าวตามมาแล้ว", 13, True),
    ("REP", "นักข่าว", 15, True),
    ("TALK1", "ขอสัมภาษณ์หน่อยค่ะ! ทำไมถึงวิ่งชนสัตว์คะ?", 14, False),
    ("TALK2", "ช่วยเล่าให้ฟังหน่อยนะคะ รู้สึกอย่างไรบ้าง...", 14, False),
    ("TALK_A", "คุยต่ออีก ", 14, False),
    ("DEAD", "ตกน้ำ! เริ่มใหม่", 28, True),
]
# digits for numbers built at run time: D13_0..9 + D13_10 ':' (HUD font), D14_0..9 + D14_10 '.' (panel font)
TEXTS += [("D13_%d" % i, c, 13, True) for i, c in enumerate("0123456789:")]
TEXTS += [("D14_%d" % i, c, 14, False) for i, c in enumerate("0123456789.")]


def main():
    import pygame
    import stage3_demo as s3
    os.makedirs(RTL, exist_ok=True)
    # ---------------------------------------------------------------- solids
    L = ["// s3_consts.vh - GENERATED by fpga/tools/stage3_assets.py from demo_py/stage3_demo.py. Do not edit.",
         "localparam integer N_SOLID = %d, N_ANIM = %d;" % (len(s3.solids), len(s3.DEF))]

    def fn(name, width, items, signed=False):
        L.append("function %s[%d:0] %s(input [7:0] i);" % ("signed " if signed else "", width - 1, name))
        assert all(-(1 << (width - 1)) <= v < (1 << width) for v in items), name
        L.append("    case (i)")
        for k, v in enumerate(items):
            L.append("        8'd%d: %s = %s;" % (k, name, ("-%d'sd%d" % (width, -v)) if v < 0 else "%d" % v))
        L.append("        default: %s = 0;" % name)
        L.append("    endcase")
        L.append("endfunction")
    S = s3.solids
    fn("so_x", 34, [q16(s["x"]) for s in S], True)
    fn("so_y", 34, [q16(s["y"]) for s in S], True)
    fn("so_w", 34, [q16(s["w"]) for s in S], True)
    fn("so_h", 34, [q16(s["h"]) for s in S], True)
    fn("so_top", 34, [q16(s["top"]) for s in S], True)
    fn("so_wall", 1, [int(s["k"] == "w") for s in S])
    D = s3.DEF
    fn("an_t", 3, [d["t"] for d in D])
    fn("an_x", 34, [q16(d["x"]) for d in D], True)
    fn("an_y", 34, [q16(d["y"]) for d in D], True)
    fn("an_y2", 34, [q16(d.get("y2", 0)) for d in D], True)
    fn("an_trig", 34, [q16(d["trig"]) for d in D], True)
    fn("an_patrol", 1, [int(d["m"] == "p") for d in D])
    fn("an_a", 34, [q16(d.get("a", 0)) for d in D], True)
    fn("an_b", 34, [q16(d.get("b", 0)) for d in D], True)
    fn("an_ph", 10, [int(round(d.get("ph", 0) * 120)) % 600 for d in D])
    # constants of s3_model.py (the RTL uses these names; values in units of 1/(120*65536) m)
    sys.path.insert(0, HERE)
    import s3_model as SM
    K = dict(Q=SM.Q, STEP=SM.STEP, T_HC=SM.T_HC, T_COY=SM.T_COY, T_TALK=SM.T_TALK, T_MSG=SM.T_MSG,
             T_GAME=SM.T_GAME, T_DEAD=SM.T_DEAD, T_TALK_HALF=SM.T_TALK_HALF, G1=SM.G1, G2=SM.G2, VJ=SM.VJ,
             GA=SM.GA, VA=SM.VA, EPS=SM.EPS, SURF_DY=SM.SURF_DY)
    for name, v in (("PW", .9), ("PH", 1.5), ("M045", .45), ("M05", .5), ("M06", .6), ("M14", 1.4), ("M24", 2.4),
                    ("M45", 4.5), ("M015", .15), ("M07", .7), ("M01", .1), ("M005", .05), ("M08", .8), ("M09", .9),
                    ("M15", 1.5), ("M2", 2), ("M3", 3), ("M6", 6), ("M20", 20), ("M230", 230), ("M249", 249),
                    ("M025", .25)):
        K[name] = SM.q(v)
    for k, v in K.items():
        L.append("localparam signed [35:0] %s = %d;" % (k, v))
    L.append("function signed [7:0] sin8(input [7:0] a);     // same table as mem/sin256.mem")
    L.append("    case (a)")
    for i in range(256):
        v = int(round(127 * math.sin(2 * math.pi * i / 256)))
        L.append("        8'd%d: sin8 = %s;" % (i, ("-8'sd%d" % -v) if v < 0 else "8'sd%d" % v))
    L.append("    endcase")
    L.append("endfunction")
    with open(os.path.join(RTL, "s3_consts.vh"), "w") as f:
        f.write("\n".join(L) + "\n")
    words = []
    for s in S:
        x0, x1 = int(round(s["x"] * 32)), int(round((s["x"] + s["w"]) * 32))
        y0, y1 = 360 - int(round((s["y"] + s["h"]) * 32)), 360 - int(round(s["y"] * 32))
        words.append((KINDS[s["k"]] << 46) | ((x0 & 8191) << 33) | ((x1 & 8191) << 20) |
                     ((max(-512, y0) & 1023) << 10) | (max(-512, min(511, y1)) & 1023))
    with open(os.path.join(MEM, "s3_solid.mem"), "w") as f:
        for w in words + [0] * (64 - len(words)):
            f.write("%013X\n" % w)
    # ---------------------------------------------------------------- Thai bitmaps
    bits, idx, meta = [], [], {}
    for tid, text, size, bold in TEXTS:
        font = s3.make_font(size, bold)
        img = font.render(text, True, (255, 255, 255), (0, 0, 0))
        w, h = img.get_width(), img.get_height()
        a = pygame.surfarray.array3d(img)[:, :, 0]          # [x][y]
        off = len(bits) // 8
        for y in range(h):
            row = [1 if a[x, y] >= 110 else 0 for x in range(w)]
            row += [0] * ((-w) % 8)
            bits.extend(row)
        idx.append((off << 16) | (min(w, 1023) << 6) | min(h, 63))
        meta[tid] = {"i": len(idx) - 1, "w": w, "h": h}
    data = [sum(bits[i + k] << (7 - k) for k in range(8)) for i in range(0, len(bits), 8)]
    assert len(data) < 65536
    with open(os.path.join(MEM, "s3_txt.mem"), "w") as f:
        for b in data:
            f.write("%02X\n" % b)
    with open(os.path.join(MEM, "s3_tidx.mem"), "w") as f:
        for v in idx + [0] * (64 - len(idx)):
            f.write("%08X\n" % v)
    with open(os.path.join(MEM, "sin256.mem"), "w") as f:
        for i in range(256):
            f.write("%02X\n" % (int(round(127 * math.sin(2 * math.pi * i / 256))) & 255))
    with open(os.path.join(HERE, "s3_text.json"), "w") as f:
        json.dump(meta, f, indent=1)
    print("stage 3 assets: %d solids, %d animals, %d Thai strings = %d bytes of bitmap"
          % (len(S), len(D), len(TEXTS), len(data)))


if __name__ == "__main__":
    main()
